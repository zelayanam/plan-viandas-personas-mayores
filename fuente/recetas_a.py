def I(n, q, t=None, est=None):
    """Ingrediente: nombre, gramos, texto visible, clave estacional."""
    if t is None:
        t = f"{q:g} g"
    d = {"n": n, "q": q, "t": t}
    if est:
        d["est"] = est
    return d


